using System.Text;
using Game.Shared;

// =====================================================================================================
//  `BL-344` step 6 — SKILL FX EXCEPTIONS: docs/data/skill_fx.csv → Game.Shared/Skills/SkillFx.g.cs
//
//  How a skill TRAVELS on screen (SkillFx: Instant / Slash / Projectile / Arrow / Beam / None) is picked
//  from its shape by SkillFxRules.AutoDelivery. This file holds ONLY the skills where that pick is wrong,
//  the owner's choice (2026-10-12): an exceptions file, the skill_faces.csv pattern, class CSVs untouched.
//
//    SKILL_ID,FX,COMMENT        FX = a SkillFx name (Auto is not allowed: delete the row instead)
//
//  --gen-fx    writes SkillFx.g.cs (unknown ids are left out and reported)
//  --check     calls FxTable.Check: unknown id, bad FX word, duplicate row, a row that only restates the
//              automatic pick, a stale .g.cs
//  --fx-list   prints every active skill with its pick, grouped — for reviewing the shape rule
// =====================================================================================================

internal static class FxTable
{
    private sealed record Row(string Id, string Fx, string Comment, int Line);

    private const string FileName = "skill_fx.csv";
    private const string Header = "SKILL_ID,FX,COMMENT";

    private static string DataPath(string repoRoot) => Path.Combine(repoRoot, "docs", "data", FileName);
    private static string GenPath(string repoRoot) => Path.Combine(repoRoot, "Game.Shared", "Skills", "SkillFx.g.cs");

    private static List<Row> Load(string repoRoot, List<string> errs)
    {
        var rows = new List<Row>();
        string path = DataPath(repoRoot);
        if (!File.Exists(path)) { errs.Add($"{FileName} is missing"); return rows; }
        var lines = File.ReadAllLines(path);
        if (lines.Length == 0 || lines[0].Trim().TrimStart('﻿') != Header)
            errs.Add($"{FileName}: the header must be exactly `{Header}`");
        for (int i = 1; i < lines.Length; i++)
        {
            if (string.IsNullOrWhiteSpace(lines[i])) continue;
            var f = SplitCsv(lines[i]);
            rows.Add(new Row(f[0].Trim(), f.Count > 1 ? f[1].Trim() : "", f.Count > 2 ? f[2].Trim() : "", i + 1));
        }
        return rows;
    }

    private static List<string> Problems(List<Row> rows)
    {
        var errs = new List<string>();
        var seen = new HashSet<string>();
        foreach (var r in rows)
        {
            string at = $"{FileName}:{r.Line} '{r.Id}'";
            if (!seen.Add(r.Id)) errs.Add($"{at}: a second row for the same skill");
            if (r.Id.Any(c => c > 127)) errs.Add($"{at}: the id has a non-ASCII character");
            var def = SkillCatalog.Get(r.Id);
            if (def is null) { errs.Add($"{at}: no such skill"); continue; }
            if (!Enum.TryParse<SkillFx>(r.Fx, ignoreCase: false, out var fx) || !Enum.IsDefined(fx) || int.TryParse(r.Fx, out _))
            {
                errs.Add($"{at}: FX '{r.Fx}' is not one of {string.Join("/", Enum.GetNames<SkillFx>().Where(n => n != "Auto"))}");
                continue;
            }
            if (fx == SkillFx.Auto) errs.Add($"{at}: FX Auto is the default — delete the row instead");
            else if (fx == SkillFxRules.AutoDelivery(def))
                errs.Add($"{at}: FX {fx} is what the shape rule already picks — the row changes nothing");
        }
        return errs;
    }

    private static string Generate(List<Row> rows)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated>\n");
        sb.Append("//   `BL-344` step 6 — GENERATED from docs/data/skill_fx.csv by\n");
        sb.Append("//     dotnet run --project tools/SkillCsvSeed -- --gen-fx\n");
        sb.Append("//   DO NOT EDIT BY HAND: edit the CSV row and regenerate. See tools/SkillCsvSeed/FxTable.cs.\n");
        sb.Append("// </auto-generated>\n");
        sb.Append("namespace Game.Shared;\n\n");
        sb.Append("internal static class SkillFxTable\n{\n");
        sb.Append("    internal static readonly System.Collections.Generic.Dictionary<string, SkillFx> Overrides = new()\n    {\n");
        foreach (var r in rows)
        {
            if (SkillCatalog.Get(r.Id) is null) continue;
            if (!Enum.TryParse<SkillFx>(r.Fx, out var fx) || !Enum.IsDefined(fx) || fx == SkillFx.Auto) continue;
            sb.Append("        [\"").Append(r.Id).Append("\"] = SkillFx.").Append(fx).Append(",\n");
        }
        sb.Append("    };\n}\n");
        return sb.ToString();
    }

    internal static int Gen(string repoRoot)
    {
        var errs = new List<string>();
        var rows = Load(repoRoot, errs);
        errs.AddRange(Problems(rows));
        foreach (var e in errs) Console.WriteLine("  🟡 FX " + e);
        File.WriteAllText(GenPath(repoRoot), Generate(rows));
        Console.WriteLine($"SkillFx.g.cs: {rows.Count} exception row(s), {errs.Count} problem(s).");
        return errs.Count == 0 ? 0 : 1;
    }

    /// <summary>For `--check`: every problem plus a stale generated file. Returns the defect count.</summary>
    internal static int Check(string repoRoot)
    {
        var errs = new List<string>();
        var rows = Load(repoRoot, errs);
        errs.AddRange(Problems(rows));
        string gen = GenPath(repoRoot);
        if (!File.Exists(gen) || File.ReadAllText(gen).Replace("\r\n", "\n") != Generate(rows))
            errs.Add("SkillFx.g.cs is STALE — run `SkillCsvSeed -- --gen-fx`");
        // A literal `Fx = ...` in a SkillDef would set the look behind the file's back: it shows up as a def whose
        // Fx is authored but which has no row.
        var inFile = rows.Select(r => r.Id).ToHashSet();
        foreach (var def in SkillCatalog.AllSkills.Where(d => d.Fx != SkillFx.Auto && !inFile.Contains(d.Id)))
            errs.Add($"'{def.Id}' has Fx = {def.Fx} set in code — it belongs in {FileName}");
        foreach (var e in errs) Console.WriteLine("  🟡 FX " + e);
        Console.WriteLine($"fx ({FileName}): {rows.Count} exception row(s), {errs.Count} problem(s).");
        return errs.Count;
    }

    /// <summary>`--fx-list`: every skill a player, mob or NPC can actually cast, with the look it draws.</summary>
    internal static int List()
    {
        var groups = SkillCatalog.AllSkills
            .Where(d => d.Category != SkillCategory.Passive)
            .GroupBy(SkillFxRules.Delivery)
            .OrderBy(g => g.Key);
        foreach (var g in groups)
        {
            Console.WriteLine($"== {g.Key} ({g.Count()})");
            foreach (var d in g.OrderBy(d => d.Category).ThenBy(d => d.Id))
                Console.WriteLine($"   {d.Id,-34} {d.Category,-8} range {d.Range,4:0} r {d.AreaRadius,4:0}"
                                  + (d.AreaAtTarget ? "@tgt" : "    ") + $" {d.TargetMode,-15} {d.RequiredWeapon}"
                                  + (d.Fx != SkillFx.Auto ? "   [authored]" : ""));
        }
        return 0;
    }

    private static List<string> SplitCsv(string line)
    {
        var outp = new List<string>();
        var sb = new StringBuilder();
        bool q = false;
        for (int i = 0; i < line.Length; i++)
        {
            char c = line[i];
            if (q)
            {
                if (c == '"' && i + 1 < line.Length && line[i + 1] == '"') { sb.Append('"'); i++; }
                else if (c == '"') q = false;
                else sb.Append(c);
            }
            else if (c == '"') q = true;
            else if (c == ',') { outp.Add(sb.ToString()); sb.Clear(); }
            else sb.Append(c);
        }
        outp.Add(sb.ToString());
        return outp;
    }
}
